"""Compile the reference's step-4 contracts into deterministic Lua data."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "docs/reference/wukong/assets"
TARGET = ROOT / "unity/Assets/WuKong/Lua/Shared/Modules/CombatConfig.lua"


def clean(value):
    if isinstance(value, dict):
        return {k: clean(v) for k, v in value.items() if k not in {
            "source", "schema", "meta", "assumptions", "contributions", "timeline",
            "notes", "note", "rule", "costFormula", "staminaCostEffect",
        }}
    if isinstance(value, list):
        return [clean(v) for v in value]
    return value


def lua(value):
    if value is None:
        return "nil"
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, (int, float)):
        return repr(value)
    if isinstance(value, str):
        return json.dumps(value, ensure_ascii=False)
    if isinstance(value, list):
        return "{" + ",".join(map(lua, value)) + "}"
    return "{" + ",".join("[" + lua(k) + "]=" + lua(v) for k, v in value.items()) + "}"


def main():
    player = json.loads((SOURCE / "data/player.json").read_text())
    tiger = json.loads((SOURCE / "data/tiger.json").read_text())
    anims = json.loads((SOURCE / "player/wukong.anims.json").read_text())
    tiger_anims = json.loads((SOURCE / "tiger/tiger.anims.json").read_text())
    clips = {}
    event_types = {"hit", "rotate", "cost", "comboWindow", "inputBuffer",
                   "dodgeWindow", "dodgeInputBuffer", "itemWindow", "moveWindow",
                   "hitCancel", "iframe", "focus", "heal", "playRate", "speedRate",
                   "superArmor", "rootMotionScale", "slowTime"}
    for name, clip in anims["clips"].items():
        clips[name] = {k: clip[k] for k in ("duration", "rateScale", "loop", "rootMotion", "sections") if k in clip}
        clips[name]["events"] = [e for e in clip.get("events", []) if e["type"] in event_types]
    data = clean({
        "player": player, "bossStats": tiger["stats"],
        "damageParams": tiger["damageModel"]["params"],
        "armor": {k: v["value"] for k, v in tiger["poise"]["superArmorLevels"].items()},
        "actions": anims["extra"]["actions"], "clips": clips,
        "capsule": anims["capsule"], "bossCapsule": tiger_anims["capsule"],
        "gait": anims["extra"]["locomotion"].get("gaitCurves", {}),
        "perfect": anims["extra"]["perfectDodge"],
    })
    TARGET.write_text("-- Generated by tools/prepare_combat.py from the reference contracts.\nreturn " + lua(data) + "\n")
    print(json.dumps({"target": str(TARGET), "clips": len(clips), "bytes": TARGET.stat().st_size}))


if __name__ == "__main__":
    main()
