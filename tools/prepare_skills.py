"""Compile step-6 skill contracts without discarding gameplay notify types."""
import json
from pathlib import Path
from prepare_combat import clean, lua

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "docs/reference/wukong/assets"
TARGET = ROOT / "unity/Assets/WuKong/Lua/Shared/Modules"


def main():
    data = {name: clean(json.loads((SRC / f"data/{name}.json").read_text()))
            for name in ("stances", "spells", "bianhua")}
    clips, forms = {}, {}
    for name, path in (("stances", "player/stances"), ("spells", "player/spells"),
                       ("transition", "player/bianhua"), ("lang", "transform/gycy_lang"),
                       ("she", "spirit/gycy_she"), ("snake", "spirit/gycy_shebang")):
        source = json.loads((SRC / f"{path}.anims.json").read_text())
        forms[name] = clean({"capsule": source["capsule"], "actions": source.get("extra", {}).get("actions", {})})
        for key, value in source["clips"].items():
            clips[key] = clean({k: v for k, v in value.items()
                                if k in {"duration", "rateScale", "loop", "rootMotion", "sections", "events"}})
    data.update(clips=clips, forms=forms)
    costs = {}
    def visit(value):
        if isinstance(value, dict):
            for row in value.get("costWindows", []):
                if row.get("effect") is not None and row.get("value") is not None:
                    costs[str(row["effect"])] = row["value"]
            for row in value.get("loopCostWindows", []):
                costs[str(row["effect"])] = value.get("loopCost", 0)
            for child in value.values():
                visit(child)
        elif isinstance(value, list):
            for child in value:
                visit(child)
    visit(data["stances"])
    data["stanceCosts"] = costs
    # The exported base montages omit the Vigor CostAttr rows. Their effect IDs
    # encode the owning skill; use its first energy row when no notify lists one.
    vigor_by_skill = {}
    for effect, value in sorted(data["bianhua"]["spirit"]["energy"]["gainByEffect"].items(), key=lambda item: int(item[0])):
        vigor_by_skill.setdefault(str(int(effect) // 100), value)
    data["vigorBySkill"] = vigor_by_skill
    (TARGET / "SkillsConfig.lua").write_text(
        "-- Generated by tools/prepare_skills.py from source skill and montage contracts.\nreturn " + lua(data) + "\n")
    mapping = {"source": "stances.js / spells.js / transform.js / spirit.js",
               "clips": {k: len(json.loads((SRC / f"{p}.anims.json").read_text())["clips"])
                         for k, p in (("stances", "player/stances"), ("spells", "player/spells"),
                                      ("transition", "player/bianhua"), ("lang", "transform/gycy_lang"),
                                      ("she", "spirit/gycy_she"), ("snake", "spirit/gycy_shebang"))},
               "notifyTypes": sorted({e["type"] for c in clips.values() for e in c.get("events", [])}),
               "inferences": ["Base montage Vigor rows omitted: landed hit falls back to the first gainByEffect row whose ID encodes the skill."],
               "presentationDeferredToStep7": ["particles", "audio", "material curves", "dissolve"]}
    (ROOT / "docs/reference/step6-skill-mapping.json").write_text(json.dumps(mapping, ensure_ascii=False, indent=2) + "\n")
    print(json.dumps({"clips": len(clips), "stanceCosts": len(costs), "notifyTypes": mapping["notifyTypes"]}))


if __name__ == "__main__":
    main()
