"""Compile tiger contracts and record every source skill's migration status."""
import json
from pathlib import Path
from prepare_combat import clean, lua

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "docs/reference/wukong/assets"


def main():
    data = json.loads((SRC / "data/tiger.json").read_text())
    anims = json.loads((SRC / "tiger/tiger.anims.json").read_text())
    clips = {}
    ignored = []
    supported = {"rotate", "hit", "comboWindow", "superArmor", "buff", "warning",
                 "bullet", "effect", "behavior", "jumpSectionIfBuff",
                 "destroyProjectile", "speedRate", "playRate", "noHitMove",
                 "collision", "bodyCollisionScale", "stoneSkin"}
    for name, source in anims["clips"].items():
        clip = {k: source[k] for k in ("duration", "rateScale", "loop", "rootMotion", "sections") if k in source}
        rows = data["montages"].get(name, {})
        clip["events"] = [dict(e) for e in source.get("events", []) if e["type"] in supported]
        # Anim export's generic moveScale loses axes/pure-scale. Use the montage rows.
        for row in rows.get("rootMotionScale", []):
            clip["events"].append(dict(row, type="rootMotionScale"))
        for e in clip["events"]:
            if e["type"] == "bullet":
                matches = [r for r in rows.get("bullets", []) if abs(r["start"] - e["start"]) < .02]
                if matches:
                    e.update(matches[0])
                    e["bulletId"] = matches[0]["bullet"]
            if e["type"] == "bullet" and e.get("bulletId") is None:
                ignored.append({"clip": name, "time": e["start"], "reason": "reference bulletNoId: empty projectile notify"})
        clip["events"] = [e for e in clip["events"] if e["type"] != "bullet" or e.get("bulletId") is not None]
        clips[name] = clip
    result = clean({k: data[k] for k in ("stats", "poise", "phases", "skills", "effects", "buffs", "bullets", "ai")})
    result["clips"] = clean(clips)
    result["capsule"] = clean(anims["capsule"])
    result["idle"] = "AS_HFM_Hu_Stone_Bstd_01"
    result["freeMove"] = "Hu_stone_01_MMF_shexing"
    result["lockMove"] = "Hu_stone_01_MMS_mizi"
    result["stone"] = clean(json.loads((SRC / "vfx/vfx.json").read_text())["stone"])
    target = ROOT / "unity/Assets/WuKong/Lua/Shared/Modules/BossConfig.lua"
    target.write_text("-- Generated by tools/prepare_boss.py; source units are metres and seconds.\nreturn " + lua(result) + "\n")
    mapping = []
    for sid, spec in data["skills"].items():
        clip = clips.get(spec["clip"])
        mapping.append({"skill": sid, "clip": spec["clip"], "referencedBy": spec.get("referencedBy", []),
                        "implemented": clip is not None, "duration": clip["duration"] if clip else None,
                        "sections": clip.get("sections", []) if clip else [],
                        "events": {k: sum(e["type"] == k for e in clip["events"]) for k in sorted(supported)}
                        if clip else {}})
    report = {"source": "src/boss.js + hazards.js + stone.js; assets/data/tiger.json + tiger.anims.json",
              "skills": mapping, "droppedAsInReference": data["skillsDropped"],
              "ignoredEmptyNotifiesAsInReference": ignored,
              "presentationDeferredToStep7": ["audio", "particles", "material notify curves", "death dissolve"],
              "runtimeCoverage": "filled separately by step5-runtime-evidence.json"}
    path = ROOT / "docs/reference/step5-skill-mapping.json"
    path.write_text(json.dumps(report, ensure_ascii=False, indent=2) + "\n")
    print(json.dumps({"config": str(target), "clips": len(clips), "skills": len(mapping),
                      "missing": [m["skill"] for m in mapping if not m["implemented"]]}))


if __name__ == "__main__":
    main()
